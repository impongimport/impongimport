/** word joiner — อยู่ระหว่างตัวอักษรแล้วห้ามเบราว์เซอร์ตัดบรรทัดตรงนั้น */
const WORD_JOINER = '⁠'

/**
 * คำประสมที่ห้ามตัดบรรทัดกลางคำ
 *
 * ภาษาไทยไม่เว้นวรรคระหว่างคำ เบราว์เซอร์จึงตัดบรรทัดโดยใช้พจนานุกรม
 * ผลคือคำประสมอย่าง "สถานพยาบาล" ถูกแยกเป็น "สถาน" + "พยาบาล" คนละบรรทัด ซึ่งอ่านแล้วสะดุด
 *
 * เรียงจากคำยาวไปสั้น เพราะแทนคำยาวก่อนแล้วคำสั้นที่ซ้อนอยู่จะไม่ถูกจับซ้ำ
 */
const COMPOUNDS = [
  'เครื่องกระตุ้นไฟฟ้า',
  'อุปกรณ์การแพทย์',
  'ศูนย์การแพทย์',
  'สถานพยาบาล',
  'ชุดครอบแก้ว',
  'จัดจำหน่าย',
  'แคตตาล็อก',
  'ใบเสนอราคา',
  'ใบกำกับภาษี',
  'เข็มฝังเข็ม',
  'ผู้เสียภาษี',
  'โรงพยาบาล',
  'แผนจีน',
]

/** ใส่ word joiner ในคำประสม ใช้กับข้อความตัวใหญ่ที่ตัดบรรทัดผิดแล้วเห็นชัด */
export function keepWords(text: string) {
  return COMPOUNDS.reduce(
    (acc, word) => acc.split(word).join([...word].join(WORD_JOINER)),
    text
  )
}
